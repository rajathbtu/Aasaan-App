const romanHindiWords_set = new Set(Object.keys(romanHindiWords_dict));

export function transliterateRomanizedHindi(text: string): string | null {
  let transliteratedWordCount = 0;
  const transliterated = text.replace(/[A-Za-z]+/g, (word) => {
    const normalizedWord = word.toLowerCase();
    if (!romanHindiWords_set.has(normalizedWord)) return word;

    transliteratedWordCount += 1;
    return romanHindiWords_dict[normalizedWord]
      || Sanscript.t(normalizedWord, 'itrans', 'devanagari', { syncope: true });
  });

  return transliteratedWordCount > 0 && transliterated !== text
    ? transliterated
    : null;
}
