/**
 * Displays in‑app notifications generated by the backend.
 * Matches the approved design:
 * back + title + mark-all-read header, category tabs, Today/Earlier
 * groups, icon-tile cards with clock/calendar timestamps, unread dot
 * and chevron, plus a tappable detail sheet.
 */

type FilterKey = 'all' | 'work' | 'updates';

type TypeStyle = {
  icon: string;
};

const TYPE_STYLES: Record<string, TypeStyle> = {
  newRequest: { icon: 'notif-briefcase' },
  requestAccepted: { icon: 'notif-check-circle' },
  ratingPrompt: { icon: 'bell' },
  boostPromotion: { icon: 'bell' },
  autoClosed: { icon: 'bell' },
  planPromotion: { icon: 'crown' },
};

const DEFAULT_TYPE_STYLE: TypeStyle = { icon: 'bell' };

const getTypeStyle = (type: string): TypeStyle => TYPE_STYLES[type] ?? DEFAULT_TYPE_STYLE;

/** Backend notification types that belong to the “Work Requests” tab. */
const WORK_TYPES = new Set(['newRequest', 'requestAccepted', 'autoClosed']);

const getNotificationCategory = (item: any): Exclude<FilterKey, 'all'> =>
  item?.data?.category === 'work' || item?.data?.category === 'updates'
    ? item.data.category
    : WORK_TYPES.has(item?.type)
      ? 'work'
      : 'updates';

type ListRow =
  | { kind: 'header'; key: string; title: string; count: number }
  | { kind: 'notification'; key: string; item: any; isToday: boolean };

const SkeletonCard: React.FC = () => {
  const opacity = useRef(new Animated.Value(0.45)).current;
  useEffect(() => {
    const loop = Animated.loop(
      Animated.sequence([
        Animated.timing(opacity, { toValue: 1, duration: 700, useNativeDriver: true }),
        Animated.timing(opacity, { toValue: 0.45, duration: 700, useNativeDriver: true }),
      ])
    );
    loop.start();
    return () => loop.stop();
  }, [opacity]);

  return (
    <Animated.View style={[styles.card, styles.skeletonCard, { opacity }]}>
      <View style={[styles.iconTile, styles.skeletonBlock]} />
      <View style={styles.cardContent}>
        <View style={[styles.skeletonBlock, { height: 14, width: '55%', marginBottom: 8 }]} />
        <View style={[styles.skeletonBlock, { height: 11, width: '90%', marginBottom: 4 }]} />
        <View style={[styles.skeletonBlock, { height: 11, width: '65%' }]} />
      </View>
    </Animated.View>
  );
};

const NotificationsScreen: React.FC = () => {
  const { token, user } = useAuth();
  const navigation = useNavigation<any>();
  const { t } = useI18n();
  const timeAgo = buildTimeAgo(t);
  const { height: windowHeight } = useWindowDimensions();
  const { refresh: refreshUnreadCount } = useNotificationCount();
  const [notifications, setNotifications] = useState<any[]>([]);
  const [loading, setLoading] = useState(false);
  const [refreshing, setRefreshing] = useState(false);
  const [notificationError, setNotificationError] = useState<unknown | null>(null);
  const [selectedItem, setSelectedItem] = useState<any>(null);
  const [activeFilter, setActiveFilter] = useState<FilterKey>('all');
  const cacheKey = user?.id ? offlineCacheKey('notifications', user.id) : null;

  const fetchNotifications = async (isRefresh = false) => {
    if (!token || !cacheKey) return;
    try {
      if (isRefresh) setRefreshing(true);
      else setLoading(true);
      const cached = await readOfflineCache<any[]>(cacheKey);
      if (cached && !isRefresh) {
        setNotifications(cached);
        setLoading(false);
      }
      const list = await getNotifications(token);
      setNotifications(list);
      await writeOfflineCache(cacheKey, list);
      setNotificationError(null);
      refreshUnreadCount();
    } catch (err) {
      const cached = await readOfflineCache<any[]>(cacheKey);
      if (cached) setNotifications(cached);
      setNotificationError(err);
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useFocusEffect(
    useCallback(() => {
      void fetchNotifications();
      return () => { refreshUnreadCount(); };
    }, [token, cacheKey])
  );

  const unreadCount = useMemo(
    () => notifications.filter((n) => !n.read).length,
    [notifications]
  );

  /** Total counts per category, shown on the filter tabs like the approved design. */
  const categoryCounts = useMemo(() => {
    let work = 0;
    let updates = 0;
    for (const item of notifications) {
      if (getNotificationCategory(item) === 'work') work += 1;
      else updates += 1;
    }
    return { all: notifications.length, work, updates };
  }, [notifications]);

  const markAllRead = async () => {
    if (!token || unreadCount === 0) return;
    try {
      await markAllNotificationsRead(token);
      setNotifications((current) => current.map((n) => ({ ...n, read: true })));
      setNotificationError(null);
      refreshUnreadCount();
      fetchNotifications();
    } catch (err) {
      setNotificationError(err);
    }
  };

  const handleNotificationPress = (item: any) => {
    const requestId = item?.data?.requestId || item?.request?.id;
    if (!item.read && token) {
      setNotifications((current) => current.map((n) => (n.id === item.id ? { ...n, read: true } : n)));
      void markNotificationRead(token, item.id)
        .then(() => refreshUnreadCount())
        .catch(() => {});
    }
    setSelectedItem(item);
    if (!user?.role || typeof requestId !== 'string') return;
    const target = getNotificationNavigationTarget(user.role, item.type, requestId);
    if (target) navigation.navigate(target.screen, target.params);
  };

  const rows = useMemo<ListRow[]>(() => {
    const startOfToday = new Date();
    startOfToday.setHours(0, 0, 0, 0);

    const filteredNotifications =
      activeFilter === 'all'
        ? notifications
        : notifications.filter((item) => getNotificationCategory(item) === activeFilter);

    const buckets: { key: string; title: string; data: any[]; isToday: boolean }[] = [
      { key: 'today', title: t('notifications.today'), data: [], isToday: true },
      { key: 'earlier', title: t('notifications.earlier'), data: [], isToday: false },
    ];

    for (const item of filteredNotifications) {
      const created = item?.createdAt ? new Date(item.createdAt) : null;
      const time = created?.getTime?.() || 0;
      if (!time || time >= startOfToday.getTime()) buckets[0].data.push(item);
      else buckets[1].data.push(item);
    }

    const result: ListRow[] = [];
    for (const bucket of buckets) {
      if (bucket.data.length === 0) continue;
      result.push({ kind: 'header', key: bucket.key, title: bucket.title, count: bucket.data.length });
      for (const item of bucket.data) {
        result.push({ kind: 'notification', key: item.id, item, isToday: bucket.isToday });
      }
    }
    return result;
  }, [notifications, activeFilter, t]);

  const renderNotificationRow = (item: any, isToday: boolean) => {
    const { icon } = getTypeStyle(item.type || '');
    const unread = !item.read;
    return (
      <TouchableOpacity
        activeOpacity={0.85}
        onPress={() => handleNotificationPress(item)}
        style={[styles.card, unread ? styles.cardUnread : styles.cardRead]}
        accessibilityRole="button"
        accessibilityLabel={`${item.title}. ${item.message}`}
      >
        <View style={styles.iconTile}>
          <SvgIcon name={icon as any} size={23} color={N.primary} />
        </View>
        <View style={styles.cardContent}>
          <Text style={styles.cardTitle} numberOfLines={2} ellipsizeMode="tail">
            {item.title}
          </Text>
          <Text style={styles.cardMessage}>{item.message}</Text>
          <View style={styles.timeRow}>
            <SvgIcon name={isToday ? 'clock' : 'notif-calendar'} size={14} color={N.muted} style={styles.timeIcon} />
            <Text style={styles.cardTime} numberOfLines={1} ellipsizeMode="tail">
              {timeAgo(item.createdAt)}
            </Text>
          </View>
        </View>
        <View style={styles.cardTrailing}>
          {unread && <View style={styles.unreadDot} />}
          <SvgIcon name="notif-chevron-right" size={15} color={N.muted} style={styles.chevron} />
        </View>
      </TouchableOpacity>
    );
  };

  const renderItem = ({ item }: { item: ListRow }) => {
    if (item.kind === 'header') {
      return (
        <View style={styles.sectionHeader}>
          <Text style={styles.sectionHeaderText} numberOfLines={1} ellipsizeMode="tail">
            {item.title}
          </Text>
          <View style={styles.sectionCount}>
            <Text style={styles.sectionCountText} numberOfLines={1}>
              {item.count}
            </Text>
          </View>
        </View>
      );
    }
    return renderNotificationRow(item.item, item.isToday);
  };

  const renderDetailSheet = () => {
    if (!selectedItem) return null;
    return (
      <Modal
        transparent
        visible={true}
        onRequestClose={() => setSelectedItem(null)}
        style={styles.overlay}
      >
        <TouchableOpacity style={styles.overlayBackdrop} onPress={() => setSelectedItem(null)} />
        <View style={styles.sheet}>
          <View style={styles.sheetTop}>
            <Text style={[styles.sheetTitle, { minWidth: 0 }]} numberOfLines={2} ellipsizeMode="tail">
              {selectedItem.title || t('notifications.title')}
            </Text>
            <TouchableOpacity onPress={() => setSelectedItem(null)} style={styles.sheetClose} activeOpacity={0.7} accessibilityLabel="Close">
              <SvgIcon name="notif-close" size={17} color={N.muted} />
            </TouchableOpacity>
          </View>
          <ScrollView
            style={{ maxHeight: Math.max(140, Math.round(windowHeight * 0.42)) }}
            showsVerticalScrollIndicator={false}
            bounces={false}
          >
            <Text style={[styles.sheetDesc, { minWidth: 0 }]}>
              {selectedItem.message}
            </Text>
            <View style={styles.sheetTimeRow}>
              <SvgIcon name="clock" size={14} color={N.muted} />
              <Text style={styles.sheetTime} numberOfLines={1} ellipsizeMode="tail">
                {timeAgo(selectedItem.createdAt)}
              </Text>
            </View>
          </ScrollView>
          <TouchableOpacity style={styles.sheetAction} onPress={() => setSelectedItem(null)} activeOpacity={0.8}>
            <Text style={styles.sheetActionText} numberOfLines={1}>
              {t('notifications.gotIt')}
            </Text>
          </TouchableOpacity>
        </View>
      </Modal>
    );
  };

  const tabs: Array<{ key: FilterKey; label: string; count: number; icon?: string }> = [
    { key: 'all', label: t('notifications.tabAll'), count: categoryCounts.all },
    { key: 'work', label: t('notifications.tabWork'), count: categoryCounts.work, icon: 'notif-briefcase' },
    { key: 'updates', label: t('notifications.tabUpdates'), count: categoryCounts.updates, icon: 'bell' },
  ];

  const emptyCopy =
    activeFilter === 'all'
      ? { title: t('notifications.emptyTitle'), description: t('notifications.emptySubtitle') }
      : { title: t('notifications.filterEmptyTitle'), description: t('notifications.filterEmptySubtitle') };

  if (loading) {
    return (
      <View style={styles.container}>
        <Header title={t('notifications.title')} showBackButton={true} showNotification={false} titleStyle={styles.headerTitleLg} />
        <View style={styles.skeletonWrap}>
          <SkeletonCard />
          <SkeletonCard />
          <SkeletonCard />
          <SkeletonCard />
          <SkeletonCard />
        </View>
      </View>
    );
  }

  return (
    <View style={styles.container}>
      <Header
        title={t('notifications.title')}
        showBackButton={true}
        showNotification={false}
        titleStyle={styles.headerTitleLg}
        customRightComponent={
          <TouchableOpacity
            style={[styles.markButton, unreadCount === 0 && styles.markButtonDisabled]}
            onPress={markAllRead}
            activeOpacity={0.8}
            disabled={unreadCount === 0}
            accessibilityLabel={t('notifications.markAllRead')}
          >
            <SvgIcon name="notif-check-double" size={16} color={unreadCount === 0 ? N.muted : N.markText} />
            <Text style={[styles.markText, unreadCount === 0 && styles.markTextDisabled]} numberOfLines={1}>
              {t('notifications.markAllRead')}
            </Text>
          </TouchableOpacity>
        }
      />

      {/* Scrollable filter tabs — pills size to content so long labels never
          squeeze or overflow on 360 dp phones. */}
      <ScrollView
        horizontal
        showsHorizontalScrollIndicator={false}
        style={styles.tabsScroll}
        contentContainerStyle={styles.tabsWrap}
      >
        {tabs.map((tab) => {
          const active = activeFilter === tab.key;
          return (
            <TouchableOpacity
              key={tab.key}
              style={[styles.tab, active && styles.tabActive]}
              onPress={() => setActiveFilter(tab.key)}
              activeOpacity={0.8}
              accessibilityRole="button"
              accessibilityState={{ selected: active }}
              accessibilityLabel={`${tab.label} ${tab.count}`}
            >
              {tab.icon && (
                <SvgIcon name={tab.icon as any} size={15} color={active ? '#FFFFFF' : N.ink} />
              )}
              <Text style={[styles.tabText, active && styles.tabTextActive]} numberOfLines={1}>
                {tab.label}
              </Text>
              <Text style={[styles.tabCount, active && styles.tabCountActive]} numberOfLines={1}>
                ({tab.count})
              </Text>
            </TouchableOpacity>
          );
        })}
      </ScrollView>

      <FlatList
        data={rows}
        keyExtractor={(row) => row.key}
        renderItem={renderItem}
        ListEmptyComponent={
          <EmptyState
            icon="notifications-off-outline"
            title={emptyCopy.title}
            description={emptyCopy.description}
          />
        }
        refreshControl={
          <RefreshControl
            refreshing={refreshing}
            onRefresh={() => fetchNotifications(true)}
            tintColor={N.primary}
            colors={[N.primary]}
          />
        }
        contentContainerStyle={{ paddingBottom: 100 }}
        showsVerticalScrollIndicator={false}
      />
      <ErrorBanner error={notificationError} onRetry={fetchNotifications} />
      <SafeBottomBanner />
      {renderDetailSheet()}
    </View>
  );
};

