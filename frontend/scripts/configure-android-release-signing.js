#!/usr/bin/env node
/**
 * Injects a real RELEASE signing config into the Expo-prebuilt Android project.
 *
 * Why this exists:
 * The app uses the Expo managed workflow (CNG). `frontend/android/` is NOT
 * committed to git, so `npx expo prebuild` regenerates `android/app/build.gradle`
 * on every CI run from Expo's template. That template ships:
 *
 *     release { signingConfig signingConfigs.debug }
 *
 * i.e. a "release" build signed with the well-known React Native debug key,
 * which Google Play Console rejects. Because the file is regenerated we cannot
 * just commit a patched build.gradle -- we have to patch it after every prebuild.
 *
 * Credentials are read from the environment (populated from GitHub Secrets by
 * the workflow) and written to `android/keystore.properties`, which is
 * git-ignored. Secret values are NEVER printed to the log.
 *
 * Usage:
 *   node scripts/configure-android-release-signing.js --require
 *   node scripts/configure-android-release-signing.js --optional
 *
 *   --require  fail if credentials are missing (used for main/release builds,
 *              so a misconfigured secret can never silently yield an
 *              unsigned AAB)
 *   --optional skip quietly if credentials are missing (used for branch/PR
 *              builds, where we only produce a debug APK)
 */

const fs = require('fs');
const path = require('path');

const ANDROID_DIR = path.join(__dirname, '..', 'android');
const APP_GRADLE = path.join(ANDROID_DIR, 'app', 'build.gradle');
const KEYSTORE_PROPS = path.join(ANDROID_DIR, 'keystore.properties');
const KEYSTORE_FILE = path.join(ANDROID_DIR, 'app', 'aasaan-upload.keystore');

const MARKER = 'Injected by scripts/configure-android-release-signing.js';

const RELEASE_SIGNING_CONFIG = `        // --- ${MARKER} (CI only) ---
        // Credentials live in android/keystore.properties, which is git-ignored.
        release {
            def keystorePropertiesFile = rootProject.file("keystore.properties")
            if (keystorePropertiesFile.exists()) {
                def keystoreProperties = new Properties()
                keystorePropertiesFile.withInputStream { keystoreProperties.load(it) }
                storeFile file(keystoreProperties['storeFile'])
                storePassword keystoreProperties['storePassword']
                keyAlias keystoreProperties['keyAlias']
                keyPassword keystoreProperties['keyPassword']
            } else {
                throw new GradleException(
                    "Release signing requested but android/keystore.properties is missing. " +
                    "Run scripts/configure-android-release-signing.js first."
                )
            }
        }
`;

function fail(message) {
  console.error(`[android-signing] ERROR: ${message}`);
  process.exit(1);
}

function readCredentials() {
  const b64 = process.env.AASAAN_ANDROID_KEYSTORE_BASE64;
  const storePassword = process.env.AASAAN_ANDROID_KEYSTORE_PASSWORD;
  const keyAlias = process.env.AASAAN_ANDROID_KEY_ALIAS;
  const keyPassword =
    process.env.AASAAN_ANDROID_KEY_PASSWORD || process.env.AASAAN_ANDROID_KEYSTORE_PASSWORD;

  const missing = [];
  if (!b64) missing.push('AASAAN_ANDROID_KEYSTORE_BASE64');
  if (!storePassword) missing.push('AASAAN_ANDROID_KEYSTORE_PASSWORD');
  if (!keyAlias) missing.push('AASAAN_ANDROID_KEY_ALIAS');
  if (!keyPassword) missing.push('AASAAN_ANDROID_KEY_PASSWORD');
  return { b64, storePassword, keyAlias, keyPassword, missing };
}

// Escapes ':' and '\' so passwords containing them cannot corrupt the
// java .properties file we generate.
const esc = (v) => String(v).replace(/\\/g, '\\\\').replace(/:/g, '\\:');

function writeKeystore(b64) {
  fs.mkdirSync(path.dirname(KEYSTORE_FILE), { recursive: true });
  fs.writeFileSync(KEYSTORE_FILE, Buffer.from(b64, 'base64'), { mode: 0o600 });
  const size = fs.statSync(KEYSTORE_FILE).size;
  if (size === 0) {
    fail('Decoded keystore is 0 bytes -- AASAAN_ANDROID_KEYSTORE_BASE64 looks invalid.');
  }
  return size;
}

function writeKeystoreProperties({ storePassword, keyAlias, keyPassword }) {
  fs.writeFileSync(
    KEYSTORE_PROPS,
    [
      '# Generated by scripts/configure-android-release-signing.js -- DO NOT COMMIT.',
      // Resolved by Gradle's `file()` relative to the android/app project dir,
      // so this must be a bare filename (the keystore lives in android/app/).
      'storeFile=aasaan-upload.keystore',
      `storePassword=${esc(storePassword)}`,
      `keyAlias=${esc(keyAlias)}`,
      `keyPassword=${esc(keyPassword)}`,
      '',
    ].join('\n')
  );
}

/**
 * Adds a `release` entry to signingConfigs and repoints the `release`
 * buildType at it. Every marker is verified -- if Expo's template changes
 * shape we fail loudly instead of silently producing a debug-signed build.
 */
function patchBuildGradle() {
  let gradle = fs.readFileSync(APP_GRADLE, 'utf8');

  // Make the patch idempotent (prebuild can reuse an existing android/ dir).
  if (gradle.includes(MARKER)) {
    gradle = gradle.replace(
      new RegExp(`\\s*// --- ${MARKER.replace(/[/.]/g, '\\$&')} \\(CI only\\) ---[\\s\\S]*?\\n        \\}\\n`),
      '\n'
    );
  }

  const SIGNING_CONFIGS_ANCHOR = 'signingConfigs {';
  const anchorIdx = gradle.indexOf(SIGNING_CONFIGS_ANCHOR);
  if (anchorIdx === -1) {
    fail('Could not find `signingConfigs {` in android/app/build.gradle (template changed?).');
  }
  const insertAt = anchorIdx + SIGNING_CONFIGS_ANCHOR.length;
  gradle = gradle.slice(0, insertAt) + '\n' + RELEASE_SIGNING_CONFIG + gradle.slice(insertAt);

  const buildTypesIdx = gradle.indexOf('buildTypes {');
  if (buildTypesIdx === -1) {
    fail('Could not find `buildTypes {` in android/app/build.gradle (template changed?).');
  }
  const releaseIdx = gradle.indexOf('release {', buildTypesIdx);
  if (releaseIdx === -1) {
    fail('Could not find the `release {` buildType in android/app/build.gradle.');
  }
  const releaseBlockEnd = gradle.indexOf('\n        }', releaseIdx);
  const releaseBlock = gradle.slice(releaseIdx, releaseBlockEnd === -1 ? undefined : releaseBlockEnd);

  // The release buildType may point at `debug` (fresh prebuild) or already at
  // `release` (this script ran before on a reused android/ dir). Both are fine;
  // anything else means the template changed shape and we must not guess.
  if (!releaseBlock.includes('signingConfigs.debug') &&
      !releaseBlock.includes('signingConfigs.release')) {
    fail(
      'The release buildType has no recognised signingConfig line. ' +
        'Refusing to guess -- inspect android/app/build.gradle manually.'
    );
  }

  gradle =
    gradle.slice(0, releaseIdx) +
    releaseBlock.replace(
      'signingConfig signingConfigs.debug',
      'signingConfig signingConfigs.release'
    ) +
    gradle.slice(releaseBlockEnd === -1 ? undefined : releaseBlockEnd);

  fs.writeFileSync(APP_GRADLE, gradle);
}

function main() {
  const requireCreds = process.argv.includes('--require');
  const optional = process.argv.includes('--optional');
  if (requireCreds === optional) {
    fail('Pass exactly one of --require or --optional.');
  }

  if (!fs.existsSync(APP_GRADLE)) {
    fail(`${APP_GRADLE} not found. Run \`npx expo prebuild --platform android\` first.`);
  }

  const creds = readCredentials();

  if (creds.missing.length > 0) {
    if (optional) {
      console.log(
        `[android-signing] No release credentials available (missing: ${creds.missing.join(
          ', '
        )}). Skipping -- no release build will be produced.`
      );
      return;
    }
    fail(
      `Missing required credential env vars: ${creds.missing.join(', ')}. ` +
        'Configure these as GitHub repository secrets (Settings > Secrets and variables > Actions).'
    );
  }

  const keystoreSize = writeKeystore(creds.b64);
  writeKeystoreProperties(creds);
  patchBuildGradle();

  console.log('[android-signing] Release signing configured.');
  console.log(
    `[android-signing]   keystore : android/app/aasaan-upload.keystore (${keystoreSize} bytes)`
  );
  console.log(`[android-signing]   alias    : ${creds.keyAlias}`);
  console.log('[android-signing]   passwords: <redacted>');
  console.log('[android-signing]   release buildType now uses signingConfigs.release');
}

main();
